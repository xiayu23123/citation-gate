"""Tune on dev, report on test, and ablate.

The fuzzy threshold is picked on bench/dev.jsonl only (max balanced accuracy).
bench/test.jsonl is scored once per configuration with that threshold.

Usage: python scripts/bench.py [--corpus corpus] [--bench bench] [--summary FILE]
"""

from __future__ import annotations

import argparse
import json
from dataclasses import replace
from pathlib import Path

from citation_gate import Corpus, Policy
from citation_gate.evaluate import load_bench, run
from citation_gate.normalize import load_critical

THRESHOLDS = [0.70, 0.75, 0.80, 0.85, 0.90, 0.95]


def configs(threshold: float) -> dict[str, Policy]:
    full = Policy(fuzzy_threshold=threshold, critical=load_critical("tcm"))
    return {
        "exact match only": replace(full, fuzzy_threshold=1.0, critical=frozenset(), detect_splices=False),
        "+ fuzzy match": replace(full, critical=frozenset(), detect_splices=False),
        "+ critical characters": replace(full, detect_splices=False),
        "+ splice detection (full)": full,
    }


def pct(x: float) -> str:
    return f"{x:.1%}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--corpus", default="corpus")
    ap.add_argument("--bench", default="bench")
    ap.add_argument("--summary", help="also append the Markdown here (e.g. $GITHUB_STEP_SUMMARY)")
    args = ap.parse_args()

    corpus = Corpus.load(args.corpus)
    bench = Path(args.bench)
    dev, test = load_bench(bench / "dev.jsonl"), load_bench(bench / "test.jsonl")

    sweep = {t: run(corpus, dev, Policy(fuzzy_threshold=t)) for t in THRESHOLDS}
    # Several thresholds can tie on dev; take the middle of the tied run rather
    # than its loosest end, which test data would punish first.
    best = max(r["balanced_accuracy"] for r in sweep.values())
    tied = [t for t in THRESHOLDS if sweep[t]["balanced_accuracy"] == best]
    chosen = tied[len(tied) // 2]

    results = {name: run(corpus, test, policy) for name, policy in configs(chosen).items()}
    full = results["+ splice detection (full)"]

    lines = [
        "# Benchmark results",
        "",
        "Generated by `scripts/bench.py`; do not edit by hand. "
        f"Corpus: {len(corpus.docs)} files, {sum(len(d.folded.text) for d in corpus.docs):,} folded characters.",
        "",
        "## Threshold, chosen on dev",
        "",
        "| fuzzy threshold | caught (recall) | false alarms | balanced acc. |",
        "|---|---|---|---|",
    ]
    for t, r in sweep.items():
        mark = " **← chosen**" if t == chosen else ""
        lines.append(f"| {t:.2f}{mark} | {pct(r['recall'])} | {pct(r['false_alarm'])} | {r['balanced_accuracy']:.3f} |")

    lines += [
        "",
        f"## Ablation on test (n={full['n']}, threshold {chosen:.2f})",
        "",
        "Each row adds one mechanism to the row above.",
        "",
        "| configuration | caught (recall) | false alarms | precision | F1 |",
        "|---|---|---|---|---|",
    ]
    for name, r in results.items():
        lines.append(f"| {name} | {pct(r['recall'])} | {pct(r['false_alarm'])} | {pct(r['precision'])} | {r['f1']:.3f} |")

    cats = list(full["by_category"])
    lines += [
        "",
        "## Flag rate by category on test",
        "",
        "Good categories (genuine, noise) should be near 0%; the rest near 100%.",
        "",
        "| category | n | " + " | ".join(results) + " |",
        "|---|---|" + "---|" * len(results),
    ]
    for c in cats:
        row = [f"{r['by_category'][c].get('flagged', 0) / r['by_category'][c]['n']:.0%}" for r in results.values()]
        lines.append(f"| {c} | {full['by_category'][c]['n']} | " + " | ".join(row) + " |")

    lines += ["", "## What the full gate called each test item", "", "| category | statuses |", "|---|---|"]
    for c in cats:
        st = ", ".join(f"{s} {k}" for s, k in sorted(full["confusion"][c].items(), key=lambda x: -x[1]))
        lines.append(f"| {c} | {st} |")

    lines += ["", f"## Errors of the full gate on test ({len(full['errors'])})", ""]
    for e in full["errors"]:
        lines.append(f"- `{e['id']}` {e['category']} → {e['status']}: {e['quote']}")

    md = "\n".join(lines) + "\n"
    (bench / "RESULTS.md").write_text(md, encoding="utf-8", newline="\n")
    (bench / "results.json").write_text(
        json.dumps({"chosen_threshold": chosen, "dev_sweep": sweep, "test": results}, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    if args.summary:
        with open(args.summary, "a", encoding="utf-8") as f:
            f.write(md)
    print(md)


if __name__ == "__main__":
    main()
